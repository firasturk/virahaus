/* The product pages run in English and Arabic. Everything they print, in both. */
export type Lang = "en" | "ar";

export const productPath = (slug: string, lang: Lang) => (lang === "ar" ? `/ar/product/${slug}` : `/product/${slug}`);

const toArabicDigits = (s: string) => s.replace(/\d/g, (d) => "٠١٢٣٤٥٦٧٨٩"[+d]);

export function price(n: number, lang: Lang) {
  return lang === "ar" ? `${toArabicDigits(n.toLocaleString("en-US"))} د.أ` : `${n.toLocaleString("en-US")} JD`;
}

export function num(n: number, lang: Lang) {
  return lang === "ar" ? toArabicDigits(String(n)) : String(n);
}

